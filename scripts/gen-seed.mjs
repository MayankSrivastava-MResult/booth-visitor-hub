// Generates db/migrations/0004_seed.sql from the game's own seed file
// (pharma-ninja-src/src/data.js), so the Hub starts with exactly the same
// 8 domains and 45 TEST questions as Pharma Ninja. Also seeds the settings
// row, consent notice version 1 and the first admin account (no password:
// set it with `npm run admin:set-password`).
//
// Usage: npm run db:gen-seed   (re-run only if data.js changes before the first migration)
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve(import.meta.dirname, '..');
const dataJs = fs.readFileSync(path.join(root, 'pharma-ninja-src/src/data.js'), 'utf8');
const ctx = {};
vm.runInNewContext(dataJs + ';this.D = SEED_DOMAINS; this.Q = SEED_QUESTIONS;', ctx);
const { D: domains, Q: questions } = ctx;

const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const arr = (a) => 'array[' + a.map(lit).join(', ') + ']::text[]';

const ADMIN_EMAIL = 'mayank.srivastava@mresult.com';

const NOTICE = [
  'I agree that MResult Technologies may store the details I have entered and use them to follow up with me after the Global Pharma Partnering Summit 2026.',
  'My first name or a nickname I choose may be shown on the Pharma Ninja game leaderboard at the MResult booth.',
  'The MResult booth team can view this record.',
  'I can ask MResult to delete my details at any time.',
].join(' ');
const MARKETING = 'MResult may also send me occasional news and updates about its services. I can unsubscribe at any time.';

let sql = `-- =====================================================================
-- 0004 SEED (generated by scripts/gen-seed.mjs from pharma-ninja-src/src/data.js; do not edit by hand)
-- Settings, consent notice v1, the first admin, and the game's 8 domains and ${questions.length} TEST questions.
-- =====================================================================

insert into hub.app_users (email, display_name, role) values (${lit(ADMIN_EMAIL)}, 'Mayank Srivastava', 'admin');

insert into hub.consent_versions (version, notice_text, marketing_text) values (1, ${lit(NOTICE)}, ${lit(MARKETING)});

insert into hub.settings (id, badge_pattern, badge_hint, consent_version, podcast_topics, demos)
values (1, '^[A-Z0-9-]{4,20}$', '4 to 20 letters, digits or hyphens', 1, '{}', '{}');

insert into hub.domains (id, name, description, icon_key, accent, enabled, sort_order) values
`;
sql += domains.map((d, i) =>
  `  (${lit(d.id)}, ${lit(d.name)}, ${lit(d.desc)}, ${lit(d.icon)}, ${lit(d.accent)}, ${d.enabled}, ${(i + 1) * 10})`).join(',\n') + ';\n\n';

sql += 'insert into hub.questions (id, domain_id, question_text, options, correct_index, difficulty, explanation, source, enabled) values\n';
sql += questions.map((q) =>
  `  (${lit(q.id)}, ${lit(q.domainId)}, ${lit(q.questionText)}, ${arr(q.options)}, ${q.correctIndex}, ${q.difficulty}, ${lit(q.explanation)}, ${lit(q.source)}, ${q.enabled})`).join(',\n') + ';\n';

const out = path.join(root, 'db/migrations/0004_seed.sql');
fs.writeFileSync(out, sql);
console.log(`Wrote ${path.relative(root, out)}: ${domains.length} domains, ${questions.length} questions`);
